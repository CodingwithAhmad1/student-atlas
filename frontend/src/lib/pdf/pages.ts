/**
 * Production address printed on the cover and in the footer. Unset until the
 * domain is final; nothing is printed while it is null.
 */
export const SITE_URL: string | null = null;

function withOpacity(doc: jsPDF, opacity: number, draw: () => void) {
  doc.saveGraphicsState();
  doc.setGState(new GState({ opacity }));
  draw();
  doc.restoreGraphicsState();
}

function rule(doc: jsPDF, x1: number, y: number, x2: number, color: RGB, width: number) {
  doc.setDrawColor(...color);
  doc.setLineWidth(width);
  doc.line(x1, y, x2, y);
}

function spaced(doc: jsPDF, text: string, x: number, y: number, align: "left" | "center" = "left") {
  doc.setCharSpace(0.6);
  doc.text(text, x, y, { align });
  doc.setCharSpace(0);
}

function fillPage(doc: jsPDF, color: RGB) {
  doc.setFillColor(...color);
  doc.rect(0, 0, PAGE_W, PAGE_H, "F");
}

/** "A", "A and B", "A, B and C" */
export function listJoin(items: string[]): string {
  return items.length <= 1 ? items.join("") : `${items.slice(0, -1).join(", ")} and ${items[items.length - 1]}`;
}

// ── Cover ──────────────────────────────────────────────────────

function drawCompassRose(doc: jsPDF, cx: number, cy: number, s: number) {
  doc.setDrawColor(...GOLD);
  doc.setLineWidth(0.6);
  doc.circle(cx, cy, s, "S");
  doc.setLineWidth(0.2);
  doc.circle(cx, cy, s * 0.86, "S");

  const point = (angle: number, reach: number, half: number, dark: RGB, light: RGB) => {
    const rad = (angle * Math.PI) / 180;
    const tip = [cx + s * reach * Math.sin(rad), cy - s * reach * Math.cos(rad)] as const;
    const side = (sign: number) => {
      const p = ((angle + sign * 90) * Math.PI) / 180;
      return [cx + s * half * Math.sin(p), cy - s * half * Math.cos(p)] as const;
    };
    const [rx, ry] = side(1);
    const [lx, ly] = side(-1);
    doc.setFillColor(...dark);
    doc.triangle(tip[0], tip[1], rx, ry, cx, cy, "F");
    doc.setFillColor(...light);
    doc.triangle(tip[0], tip[1], lx, ly, cx, cy, "F");
  };

  for (const angle of [45, 135, 225, 315]) point(angle, 0.5, 0.05, GOLD, GOLD_LIGHT);
  for (const angle of [90, 180, 270]) point(angle, 0.78, 0.09, ON_NAVY_MUTED, WHITE);
  point(0, 0.78, 0.09, RED, RED_LIGHT);

  doc.setFillColor(...GOLD);
  doc.circle(cx, cy, s * 0.05, "F");

  const r = s * 1.16;
  setFont(doc, "bold", s * 0.42, GOLD_LIGHT);
  doc.text("N", cx, cy - r + 1.5, { align: "center" });
  setFont(doc, "bold", s * 0.34, ON_NAVY_MUTED);
  doc.text("S", cx, cy + r + 1.5, { align: "center" });
  doc.text("E", cx + r, cy + 1.5, { align: "center" });
  doc.text("W", cx - r, cy + 1.5, { align: "center" });
}

export function renderCover(doc: jsPDF, nationality: string, destinations: string[], date: string) {
  fillPage(doc, NAVY);
  doc.setDrawColor(...GOLD);
  doc.setLineWidth(0.6);
  doc.rect(8, 8, PAGE_W - 16, PAGE_H - 16);
  doc.setLineWidth(0.2);
  doc.rect(11, 11, PAGE_W - 22, PAGE_H - 22);

  drawCompassRose(doc, PAGE_W / 2, 88, 28);

  setFont(doc, "bold", 38, WHITE);
  doc.text("Student Atlas", PAGE_W / 2, 152, { align: "center" });
  rule(doc, 72, 160, PAGE_W - 72, GOLD, 0.7);
  setFont(doc, "normal", 12.5, GOLD_LIGHT);
  doc.text("Your personalised guide to studying abroad", PAGE_W / 2, 170, { align: "center" });

  const boxX = MARGIN_X + 14;
  const boxW = CONTENT_W - 28;
  const boxY = 188;
  withOpacity(doc, 0.07, () => {
    doc.setFillColor(...WHITE);
    doc.roundedRect(boxX, boxY, boxW, 46, 2.5, 2.5, "F");
  });
  doc.setDrawColor(...GOLD);
  doc.setLineWidth(0.25);
  doc.roundedRect(boxX, boxY, boxW, 46, 2.5, 2.5, "S");
  rule(doc, boxX + 12, boxY + 23, boxX + boxW - 12, NAVY_SOFT, 0.3);

  const field = (label: string, value: string, y: number) => {
    setFont(doc, "bold", 7.5, GOLD);
    spaced(doc, label, PAGE_W / 2, y, "center");
    setFont(doc, "bold", 14, WHITE);
    doc.text(winAnsi(value), PAGE_W / 2, y + 8, { align: "center", maxWidth: boxW - 10 });
  };
  field("NATIONALITY", nationality, boxY + 9);
  field("DESTINATIONS", destinations.join("   ·   "), boxY + 32);

  setFont(doc, "normal", 9, GOLD_LIGHT);
  doc.text(`Prepared ${date}`, PAGE_W / 2, PAGE_H - 32, { align: "center" });
  setFont(doc, "normal", 7.5, ON_NAVY_MUTED);
  doc.text(SITE_URL ? `Generated by Student Atlas · ${SITE_URL}` : "Generated by Student Atlas", PAGE_W / 2, PAGE_H - 25, {
    align: "center",
  });
}

// ── Page titles ────────────────────────────────────────────────

/** Large page title with a gold underline, as a single kept row. */
export function pageTitleRow(doc: jsPDF, title: string, size: number = TYPE.pageTitle): Row {
  const h = size * 0.3528 + 7;
  return {
    h,
    keep: true,
    draw: (top) => {
      const base = top + size * 0.3528 * 0.8;
      setFont(doc, "bold", size, NAVY);
      doc.text(winAnsi(title), MARGIN_X, base);
      rule(doc, MARGIN_X, base + 3, MARGIN_X + 18, GOLD, 0.8);
    },
  };
}

// ── Introduction ───────────────────────────────────────────────

export interface IntroOptions {
  nationality: string;
  label: string | undefined;
  reviewedAt: string | undefined;
  destinations: string[];
  sections: { title: string; description: string }[];
  date: string;
}

function paragraphRows(ctx: Ctx, text: string, x = MARGIN_X, w = CONTENT_W): Row[] {
  return blockRows(ctx, { type: "paragraph", text }, x, w);
}

function smallHeadingRow(doc: jsPDF, text: string, x = MARGIN_X): Row {
  return {
    h: 7,
    keep: true,
    draw: (top) => {
      setFont(doc, "bold", 7.5, GOLD_DARK);
      spaced(doc, text.toUpperCase(), x, top + 4);
    },
  };
}

export function renderIntroduction(ctx: Ctx, writer: Writer, o: IntroOptions) {
  const { doc } = ctx;
  writer.newPage("front");

  const sectionNames = o.sections.map((s) => s.title.toLowerCase());
  writer.flow([
    pageTitleRow(doc, "Introduction"),
    gap(4),
    ...paragraphRows(
      ctx,
      `This report has been prepared for ${o.label ? `${o.label} nationals` : `nationals of ${o.nationality}`} considering ${listJoin(o.destinations)} as study destinations. It covers the ${listJoin(sectionNames)} ${sectionNames.length === 1 ? "section" : "sections"} of the guide, with each destination's rules side by side.`
    ),
    ...paragraphRows(
      ctx,
      "Where your nationality changes the rules, a highlighted note says so, above the general guidance it refines. Facts are drawn from official government sources, listed at the end of the report."
    ),
  ]);

  if (!o.label) {
    writer.flow(
      paragraphRows(
        ctx,
        `We don't have nationality-specific guidance for ${o.nationality} yet, so this report shows the general rules only. Whether you need a visa, and which evidence you must provide, can differ by nationality: check the official sources listed at the end.`,
        MARGIN_X + 5,
        CONTENT_W - 10
      ),
      { x: MARGIN_X, w: CONTENT_W, padTop: 4, padBottom: 2, fill: CALLOUT_BG, accent: GOLD }
    );
    writer.y += 4;
  }

  // How to read: one sample of each visual cue, with its meaning.
  const lx = MARGIN_X + 6;
  const tx = MARGIN_X + 24;
  const tw = CONTENT_W - 30;
  const cue = (sample: (top: number) => void, text: string): Row[] => {
    const lines = layoutText(doc, text, tw, TYPE.body - 0.5);
    const lh = lineHeight(TYPE.body - 0.5);
    return [
      ...lines.map((line, i) => ({
        h: lh,
        keep: i < lines.length - 1,
        draw: (top: number) => {
          if (i === 0) sample(top);
          drawTextLine(doc, line, tx, top + lh * 0.72, TYPE.body - 0.5, TEXT, GOLD_DARK);
        },
      })),
      gap(2.5),
    ];
  };
  writer.y += 3;
  writer.flow(
    [
      smallHeadingRow(doc, "How to read this report", lx),
      gap(1),
      ...cue((top) => {
        doc.setFillColor(...NAVY);
        doc.roundedRect(lx, top + 0.3, 13, 4, 0.8, 0.8, "F");
      }, "A navy bar starts the guidance for one destination."),
      ...(!o.label ? [] : cue((top) => {
        doc.setFillColor(...CALLOUT_BG);
        doc.rect(lx, top + 0.3, 13, 4, "F");
        doc.setFillColor(...GOLD);
        doc.rect(lx, top + 0.3, 1.2, 4, "F");
      }, `A gold-edged box holds notes for ${o.label} applicants.`)),
      ...cue((top) => {
        setFont(doc, "normal", 7, GOLD_DARK);
        doc.text("[3]", lx + 2, top + 2.6);
      }, "A number in brackets points to the official page in Sources at the end of the report."),
      ...(!o.label ? [] : cue((top) => {
        setFont(doc, "bold", 10, GOLD_DARK);
        doc.text("*", lx + 2, top + 4);
      }, "An asterisk marks practical guidance from experience, not from an official source.")),
    ],
    { x: MARGIN_X, w: CONTENT_W, padTop: 4, padBottom: 1.5, fill: PANEL_BG }
  );

  writer.y += 8;
  const sectionRows: Row[] = [smallHeadingRow(doc, "Sections in this report")];
  for (const s of o.sections) {
    sectionRows.push({
      h: 6,
      keep: true,
      draw: (top) => {
        doc.setFillColor(...GOLD);
        doc.circle(MARGIN_X + 1.8, top + 3.2, 1.1, "F");
        setFont(doc, "bold", TYPE.h4, NAVY);
        doc.text(s.title, MARGIN_X + 6, top + 4.3);
      },
    });
    sectionRows.push(...paragraphRows(ctx, s.description, MARGIN_X + 6, CONTENT_W - 6), gap(1));
  }
  writer.flow(sectionRows);

  const reviewed = o.reviewedAt
    ? ` Nationality-specific content for ${o.label} nationals was last reviewed on ${formatDate(o.reviewedAt)}.`
    : "";
  writer.y += 4;
  writer.flow([
    smallHeadingRow(doc, "Before you rely on it"),
    ...blockRows(
      ctx,
      {
        type: "paragraph",
        text: `This report is a reference guide, not legal advice. Immigration rules, fees and thresholds change; confirm each fact on the official page before you apply. The report reflects the guide as it stood on ${o.date}.${reviewed}`,
      },
      MARGIN_X,
      CONTENT_W
    ),
  ]);
}

export function formatDate(d: Date | string): string {
  return new Date(d).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
}

// ── Table of contents (drawn last, onto its reserved page) ─────

export interface TocEntry {
  label: string;
  level: 0 | 1;
  page: number;
  number?: number;
}

export function renderToc(doc: jsPDF, tocPage: number, entries: TocEntry[]) {
  doc.setPage(tocPage);
  let y = 26;
  pageTitleRow(doc, "Contents").draw!(y);
  y += 22;

  for (const e of entries) {
    const top = e.level === 0 ? 4 : 0;
    y += top;
    const x = e.level === 0 ? MARGIN_X : MARGIN_X + 10;
    const size = e.level === 0 ? 11.5 : 9.5;
    if (e.number != null) {
      setFont(doc, "bold", 9, GOLD_DARK);
      doc.text(String(e.number).padStart(2, "0"), MARGIN_X, y);
    }
    const labelX = e.number != null ? x + 10 : x;
    setFont(doc, e.level === 0 ? "bold" : "normal", size, e.level === 0 ? NAVY : TEXT);
    const label = winAnsi(e.label);
    doc.text(label, labelX, y);

    const pageStr = String(e.page);
    setFont(doc, e.level === 0 ? "bold" : "normal", size, e.level === 0 ? NAVY : TEXT_MUTED);
    doc.text(pageStr, PAGE_W - MARGIN_X, y, { align: "right" });

    // Dot leader between label and page number.
    setFont(doc, e.level === 0 ? "bold" : "normal", size, NAVY);
    const from = labelX + measure(doc, label) + 2.5;
    const to = PAGE_W - MARGIN_X - measure(doc, pageStr) - 2.5;
    doc.setFillColor(...HAIRLINE);
    for (let dx = from; dx < to; dx += 1.6) doc.circle(dx, y - 0.6, 0.18, "F");

    doc.link(MARGIN_X, y - 4.5, CONTENT_W, 6.5, { pageNumber: e.page });
    y += e.level === 0 ? 7.5 : 6;
  }
}

// ── Section divider (drawn last, once its pages are known) ─────

export function renderDivider(
  doc: jsPDF,
  page: number,
  number: number,
  title: string,
  description: string,
  subsections: { title: string; page: number }[]
) {
  doc.setPage(page);
  fillPage(doc, NAVY);
  rule(doc, MARGIN_X, 70, PAGE_W - MARGIN_X, GOLD, 0.6);
  rule(doc, MARGIN_X, 72.5, PAGE_W - MARGIN_X, GOLD, 0.2);

  setFont(doc, "bold", 9, GOLD);
  spaced(doc, `SECTION ${String(number).padStart(2, "0")}`, MARGIN_X, 92);
  setFont(doc, "bold", 32, WHITE);
  doc.text(title, MARGIN_X, 108);
  setFont(doc, "normal", 11.5, GOLD_LIGHT);
  const desc = doc.splitTextToSize(description, CONTENT_W - 30) as string[];
  doc.text(desc, MARGIN_X, 120, { lineHeightFactor: 1.45 });

  let y = 120 + desc.length * 6.5 + 16;
  setFont(doc, "bold", 7.5, GOLD);
  spaced(doc, "IN THIS SECTION", MARGIN_X, y);
  y += 4;
  for (const sub of subsections) {
    rule(doc, MARGIN_X, y, PAGE_W - MARGIN_X, NAVY_SOFT, 0.25);
    y += 7.5;
    setFont(doc, "normal", 11, WHITE);
    doc.text(winAnsi(sub.title), MARGIN_X, y);
    setFont(doc, "normal", 10, GOLD_LIGHT);
    doc.text(String(sub.page), PAGE_W - MARGIN_X, y, { align: "right" });
    doc.link(MARGIN_X, y - 5.5, CONTENT_W, 8, { pageNumber: sub.page });
    y += 3.5;
  }
  rule(doc, MARGIN_X, y, PAGE_W - MARGIN_X, NAVY_SOFT, 0.25);

  rule(doc, MARGIN_X, PAGE_H - 50, PAGE_W - MARGIN_X, GOLD, 0.6);
  rule(doc, MARGIN_X, PAGE_H - 47.5, PAGE_W - MARGIN_X, GOLD, 0.2);
}

// ── Sources ────────────────────────────────────────────────────

export function renderSources(ctx: Ctx, writer: Writer, sources: readonly Citation[]) {
  const { doc } = ctx;
  writer.section = "Sources";
  writer.newPage();
  writer.flow([
    pageTitleRow(doc, "Sources"),
    gap(4),
    ...paragraphRows(
      ctx,
      "Each number in brackets in this report refers to one of these official pages. Student Atlas monitors every cited page for changes; if a page has moved or changed since this report was made, the guide on the website has the current version."
    ),
    gap(3),
  ]);

  const nx = MARGIN_X;
  const tx = MARGIN_X + 10;
  const tw = CONTENT_W - 10;
  const rows: Row[] = [];
  sources.forEach((c, i) => {
    const labelSize = 9;
    const urlSize = 7.5;
    const label = layoutText(doc, plain(c.label), tw, labelSize, "bold");
    const url = layoutText(doc, c.url, tw, urlSize);
    const llh = lineHeight(labelSize);
    const ulh = lineHeight(urlSize);
    label.forEach((line, j) =>
      rows.push({
        h: llh,
        keep: true,
        draw: (top) => {
          if (j === 0) {
            setFont(doc, "bold", labelSize, GOLD_DARK);
            doc.text(`[${i + 1}]`, nx, top + llh * 0.72);
          }
          drawTextLine(doc, line, tx, top + llh * 0.72, labelSize, NAVY, GOLD_DARK);
        },
      })
    );
    url.forEach((line, j) =>
      rows.push({
        h: ulh,
        keep: j < url.length - 1,
        draw: (top) => {
          drawTextLine(doc, line, tx, top + ulh * 0.72, urlSize, TEXT_MUTED, TEXT_MUTED);
          doc.link(tx, top, tw, ulh, { url: c.url });
        },
      })
    );
    rows.push(gap(2.8));
  });
  writer.flow(rows);
}

// ── Running header and footer (last pass) ──────────────────────

export function renderHeadersAndFooters(writer: Writer, rightHeader: string, footerNote: string) {
  const { doc } = writer;
  const total = writer.pages.length;
  writer.pages.forEach((info, i) => {
    if (info.kind === "cover" || info.kind === "divider") return;
    doc.setPage(i + 1);
    if (info.kind === "content") {
      setFont(doc, "bold", 7, GOLD_DARK);
      spaced(doc, (info.section ?? "").toUpperCase(), MARGIN_X, HEADER_Y);
      setFont(doc, "normal", 7.5, TEXT_MUTED);
      doc.text(winAnsi(rightHeader), PAGE_W - MARGIN_X, HEADER_Y, { align: "right" });
      rule(doc, MARGIN_X, HEADER_Y + 2.5, PAGE_W - MARGIN_X, HAIRLINE, 0.25);
    }
    rule(doc, MARGIN_X, FOOTER_Y - 4.5, PAGE_W - MARGIN_X, GOLD, 0.3);
    setFont(doc, "normal", 7, TEXT_MUTED);
    doc.text(winAnsi(footerNote), MARGIN_X, FOOTER_Y);
    doc.text(`Page ${i + 1} of ${total}`, PAGE_W - MARGIN_X, FOOTER_Y, { align: "right" });
  });
}
